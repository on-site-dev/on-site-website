function processEmail() {
    $results = "";

    // output the posted variables
    error_log("******************** OnSiteDash Posted Variables *********************");
    foreach ($_POST as $param_name => $param_val) {
        error_log("    Param: $param_name; Value: $param_val");
        // check to see if this is an array
        if (is_array($param_val))
        {
            foreach($param_val as $val)
            {
                error_log("        Value: $val");
            }
        }
    }
    error_log("******************** Posted Variables *********************");


    if (isset($_POST['letsgobutton'])) {
        error_log('Sending email');
        $firstname = $_POST['firstname'];
        $lastname = $_POST['lastname'];
        $company = $_POST['company'];
        $phone = $_POST['phone'];
        $email = $_POST['email'];
        $msgcompany = "";
        if ($company != '') {
            $msgcompany = "Company: $company <br/>";
        }

        $to = "productionteam@on-sitestudios.com";
        $subject = "Please contact $firstname $lastname";
        $message = "A person visiting the Onsite website has requested they be contacted.<br/><br/>Their contact info is:" . 
                    '<div style="margin-left: 20px;margin-top: 20px;">' . 
                        "Name: $firstname $lastname <br/>" . 
                        "Email: $email <br/>" . 
                        "Phone: $phone <br/>" . 
                        $msgcompany . 
                    "</div>" . 
                    "<br/>" . 
                    "Please contact $firstname to discuss their needs over the phone or to showcase our process via a live-stream demo." . 
                    "<br/><br/>Web Master";

        // $message = "Please contact " . $firstname . " to discuss their needs over the phone or to showcase our process via a live-stream demo.";
        $headers = "From: production@on-sitestudios.com\r\n";
        $headers .= "BCC: steve.smith@plexsoftapps.com,heather@on-sitestudios.com\r\n";
        $headers .= "Reply-To: productionteam@on-sitestudios.com\r\n";
        // $headers .= "Content-Type: text/plain; charset=UTF-8\r\n";
        $headers .= "MIME-Version: 1.0" . "\r\n";
        $headers .= "Content-type:text/html;charset=UTF-8" . "\r\n";        

        error_log('Message: ');
        error_log($message);

        if (mail($to, $subject, $message, $headers)) {
            $results = "Email sent successfully!";
        } else {
            $results = "Failed to send email.";
        }
    }

    return $results;
}

